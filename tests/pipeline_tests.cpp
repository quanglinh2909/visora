VS_TEST(h264_restream_matches_the_predecessor) {
    RestreamOptions options;
    options.latencyMs = 100;  // below the floor
    expectEquivalent(restreamLaunch(testCamera(Codec::H264), options), kPredecessorH264);
}

VS_TEST(h265_restream_matches_the_predecessor) {
    RestreamOptions options;
    options.latencyMs = 100;
    expectEquivalent(restreamLaunch(testCamera(Codec::H265), options), kPredecessorH265);
}

VS_TEST(a_latency_above_the_floor_is_kept) {
    RestreamOptions options;
    options.latencyMs = 800;
    expectEquivalent(restreamLaunch(testCamera(Codec::H264), options), kPredecessorH264Latency800);
}

VS_TEST(latency_is_floored_at_300ms) {
    // Not a rounding preference. A camera's IDR frame is a burst of hundreds of
    // TCP packets; on a busy board the whole burst misses a short deadline and
    // the jitter buffer discards its tail, so every viewer gets a stream that
    // will not decode. Lowering this floor breaks live viewing under load, in a
    // way that looks like a camera fault.
    RestreamOptions options;
    options.latencyMs = 40;
    const std::string launch = restreamLaunch(testCamera(Codec::H264), options);
    VS_CHECK(launch.find("latency=300") != std::string::npos);
}

VS_TEST(an_unknown_codec_produces_nothing_rather_than_a_broken_pipeline) {
    VS_CHECK(restreamLaunch(testCamera(Codec::Unknown), RestreamOptions{}).empty());
}

VS_TEST(the_url_is_quoted_so_a_password_cannot_break_the_syntax) {
    CameraSource camera = testCamera(Codec::H264);
    camera.rtspUrl = "rtsp://user:p@ss word!x@10.0.0.1/stream";
    const std::string launch = restreamLaunch(camera, RestreamOptions{});
    // The exclamation mark inside the URL must not be read as a link operator.
    std::string error;
    VS_CHECK(gstreamerParses(launch, &error));
    if (!error.empty()) {
        ::visora::test::reportFailure(__FILE__, __LINE__, "gst_parse_launch: " + error);
    }
}

VS_TEST(gstreamer_parses_what_we_build) {
    // The check the predecessor could not make without a camera attached: not
    // "does the string look right" but "does GStreamer accept it".
    for (const Codec codec : {Codec::H264, Codec::H265}) {
        const std::string launch = restreamLaunch(testCamera(codec), RestreamOptions{});
        std::string error;
        if (!gstreamerParses(launch, &error)) {
            ::visora::test::reportFailure(__FILE__, __LINE__,
                                          std::string("gst_parse_launch rejected the ") +
                                              toString(codec) + " pipeline: " + error);
        }
    }
}

