// The camera pipelines, checked two ways.
//
// 1. Semantically equivalent to what the predecessor produced. Not byte-equal:
//    gst_parse_launch does not care what order properties appear in, and unlike
//    the result wire format no external consumer reads these strings. Demanding
//    byte-equality would constrain the builder for no benefit and fail on
//    changes that mean nothing.
//
// 2. GStreamer actually parses them. A string that merely looks right is worth
//    little; this is the check the predecessor could not make without a camera.

