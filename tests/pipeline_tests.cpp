    R"(( rtspsrc name=src location="rtsp://user:pa\"ss@10.0.0.1/stream" latency=300 protocols=tcp ! application/x-rtp,media=video,encoding-name=H264 ! rtph264depay ! h264parse config-interval=-1 ! rtph264pay config-interval=1 name=pay0 pt=96 ))";

