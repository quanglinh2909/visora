    R"(( rtspsrc name=src location="rtsp://user:pa\"ss@10.0.0.1/stream" latency=800 protocols=tcp ! application/x-rtp,media=video,encoding-name=H264 ! rtph264depay ! h264parse config-interval=-1 ! rtph264pay config-interval=1 name=pay0 pt=96 ))";

CameraSource testCamera(Codec codec) {
    CameraSource camera;
    camera.id = "cam-1";
    camera.rtspUrl = "rtsp://user:pa\"ss@10.0.0.1/stream";
    camera.codec = codec;
    return camera;
}

bool gstreamerParses(const std::string& description, std::string* error) {
    static bool initialised = false;
    if (!initialised) {
        gst_init(nullptr, nullptr);
        initialised = true;
    }
    GError* err = nullptr;
    GstElement* element = gst_parse_launch(description.c_str(), &err);
    if (err != nullptr) {
        *error = err->message;
        g_error_free(err);
        if (element != nullptr) gst_object_unref(element);
        return false;
    }
    if (element == nullptr) {
        *error = "gst_parse_launch returned nothing";
        return false;
    }
    gst_object_unref(element);
    return true;
}

