// One element or caps filter, decomposed.
struct Node {
    std::string head;                            // factory name, or the caps string
    std::map<std::string, std::string> properties;
};

std::string trim(const std::string& text) {
    const auto begin = text.find_first_not_of(" \t");
    if (begin == std::string::npos) return {};
    const auto end = text.find_last_not_of(" \t");
    return text.substr(begin, end - begin + 1);
}

// Splits on a delimiter, ignoring anything inside double quotes — an RTSP URL
// may contain almost anything.
std::vector<std::string> splitOutsideQuotes(const std::string& text, const std::string& delimiter) {
    std::vector<std::string> parts;
    std::string current;
    bool inQuotes = false;
    for (std::size_t i = 0; i < text.size(); ++i) {
        const char c = text[i];
        if (c == '\\' && i + 1 < text.size()) {
            current.push_back(c);
            current.push_back(text[++i]);
            continue;
        }
        if (c == '"') inQuotes = !inQuotes;
        if (!inQuotes && text.compare(i, delimiter.size(), delimiter) == 0) {
            parts.push_back(trim(current));
            current.clear();
            i += delimiter.size() - 1;
            continue;
        }
        current.push_back(c);
    }
    parts.push_back(trim(current));
    return parts;
}

std::vector<Node> parseLaunch(std::string description) {
    description = trim(description);
    if (!description.empty() && description.front() == '(') {
        description = trim(description.substr(1, description.size() - 2));
    }

    std::vector<Node> nodes;
    for (const std::string& segment : splitOutsideQuotes(description, "!")) {
        if (segment.empty()) continue;
        // A caps filter has no properties and contains a '/' in its media type.
        if (segment.find('=') == std::string::npos || segment.find('/') < segment.find(' ')) {
            nodes.push_back(Node{segment, {}});
            continue;
        }
        const std::vector<std::string> tokens = splitOutsideQuotes(segment, " ");
        Node node;
        node.head = tokens.empty() ? std::string() : tokens.front();
        for (std::size_t i = 1; i < tokens.size(); ++i) {
            const auto equals = tokens[i].find('=');
            if (equals == std::string::npos) continue;
            node.properties[tokens[i].substr(0, equals)] = tokens[i].substr(equals + 1);
        }
        nodes.push_back(std::move(node));
    }
    return nodes;
}

void expectEquivalent(const std::string& got, const std::string& want) {
    const std::vector<Node> a = parseLaunch(got);
    const std::vector<Node> b = parseLaunch(want);

    if (a.size() != b.size()) {
        ::visora::test::reportFailure(__FILE__, __LINE__,
                                      "element count differs: " + std::to_string(a.size()) +
                                          " vs " + std::to_string(b.size()) + "\n    got : " +
                                          got + "\n    want: " + want);
        return;
    }
    for (std::size_t i = 0; i < a.size(); ++i) {
        if (a[i].head != b[i].head) {
            ::visora::test::reportFailure(__FILE__, __LINE__,
                                          "element " + std::to_string(i) + " is '" + a[i].head +
                                              "', expected '" + b[i].head + "'");
            continue;
        }
        if (a[i].properties != b[i].properties) {
            std::string detail = "properties of '" + a[i].head + "' differ\n    got :";
            for (const auto& [k, v] : a[i].properties) detail += " " + k + "=" + v;
            detail += "\n    want:";
            for (const auto& [k, v] : b[i].properties) detail += " " + k + "=" + v;
            ::visora::test::reportFailure(__FILE__, __LINE__, detail);
        }
    }
}

