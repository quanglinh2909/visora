// Reference bytes produced by the PREDECESSOR implementation
// (gstreamer_c ResultPublisher::buildJson) for the fixture below.
//
// Generated by compiling and running that code, not transcribed from reading
// it. The point is to catch a difference between what the old program emitted
// and what this one does; a hand-copied expectation would only prove I read it
// the same way twice.
