// Pins the published inference-result wire format.
//
// A Python consumer parses these bytes off a Unix socket and is deployed
// separately from this program. If this test fails, that consumer misparses
// results — possibly a consumer that was not redeployed at the same time.
// Change the expectation only as part of a deliberate, coordinated protocol
// change.

#include "TestHarness.hpp"

